def cam_c2w_interp(T1: np.ndarray, T2: np.ndarray, t: float):  # T1 and T2 are camera-to-world matrices
    assert 0 <= t <= 1

    # to quaternion
    q1 = Rotation.from_matrix(T1[:3, :3])
    q2 = Rotation.from_matrix(T2[:3, :3])

    # translation vectors
    p1 = T1[:3, 3]
    p2 = T2[:3, 3]

    # rotation SLERP
    key_rots = Rotation.from_matrix([T1[:3, :3], T2[:3, :3]])
    slerp = Slerp([0, 1], key_rots)
    R_interp = slerp(t).as_matrix()

    # translation LERP
    p_interp = (1 - t) * p1 + t * p2

    # recompose
    T_interp = np.identity(4)
    T_interp[:3, :3] = R_interp
    T_interp[:3, 3] = p_interp
    return T_interp


def cam_K_interp(K1: np.ndarray, K2: np.ndarray, t: float):
    assert 0 <= t <= 1
    K_interp = (1 - t) * K1 + t * K2
    return K_interp


def get_c2w_mat(cam_dict: dict) -> np.ndarray:
    T = np.eye(4)
    T[:3, :3] = np.array(cam_dict["orientation"]).reshape(3, 3).T  # "orientation" is w2c
    T[:3, 3] = np.array(cam_dict["position"]).reshape(3)

    K = np.eye(3)
    K[0, 0] = cam_dict["focal_length"]
    K[1, 1] = cam_dict["focal_length"]
    K[0, 2] = cam_dict["principal_point"][0]
    K[1, 2] = cam_dict["principal_point"][1]

    return T, K


