    def run_trajectory(src_cam: int, tgt_cam: int, time_id: int, use_mesh: bool, save_trajectory_type: Optional[str] = None):

        src_frame_name = parser._frame_names_map[time_id, src_cam]
        tgt_frame_name = parser._frame_names_map[time_id, tgt_cam]
        image_names = [
            os.path.join(parser.data_dir, "rgb", f"{parser._factor}x", src_frame_name + ".png"),
            os.path.join(parser.data_dir, "rgb", f"{parser._factor}x", tgt_frame_name + ".png"),
        ]
        if not all([os.path.isfile(p) for p in image_names]):
            return None

        images = load_and_preprocess_images(image_names).to(f"cuda:{args.gpu_id}")
        with torch.amp.autocast("cuda", dtype=torch.bfloat16 if torch.cuda.get_device_capability()[0] >= 8 else torch.float16):
            images = images[None]  # add batch dimension
            aggregated_tokens_list, ps_idx = model.aggregator(images)
            # Predict Cameras
            pose_enc = model.camera_head(aggregated_tokens_list)[-1]
            # Extrinsic and intrinsic matrices, following OpenCV convention (camera from world)
            extrinsic, intrinsic = pose_encoding_to_extri_intri(pose_enc, images.shape[-2:])

            # Predict Depth Maps
            depth_map, depth_conf = model.depth_head(aggregated_tokens_list, images, ps_idx)

        # postprocess
        rgb = rearrange(images, "() v c h w -> v h w c", v=2, c=3).cpu().numpy()
        rgb = np.clip(255 * rgb, 0, 255).astype(np.uint8)
        _, height, width, _ = rgb.shape

        depth_map = rearrange(depth_map, "() v h w () -> v h w", v=2).cpu().numpy()

        extrinsic_3x4 = extrinsic.squeeze(0).cpu().numpy()
        intrinsic = intrinsic.squeeze(0).cpu().numpy()

        extrinsic = np.eye(4)[None, :, :].repeat(extrinsic_3x4.shape[0], axis=0)
        extrinsic[:, :3, :4] = extrinsic_3x4

        # interpolate
        poses = np.linalg.inv(extrinsic)
        poses_interp = [cam_c2w_interp(poses[0], poses[1], t) for t in np.linspace(0, 1, num=25)]
        intrinsic_interp = [cam_K_interp(intrinsic[0], intrinsic[1], t) for t in np.linspace(0, 1, num=25)]

        save_path = os.path.join(args.output_folder, f"{parser.sequence}_{src_cam}_{tgt_cam}_{time_id:05d}", "warped")
        os.makedirs(save_path, exist_ok=True)

        never_occluded = np.ones_like(depth_map[0], dtype=bool)

        # rendering
        trans_coordinates_3D_list = []
        trans_valid_list = []

        for i, (pose, intr) in enumerate(zip(poses_interp, intrinsic_interp)):
            extr = np.linalg.inv(pose)
